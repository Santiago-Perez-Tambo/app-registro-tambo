CREATE POLICY con_ver ON control_lechero FOR SELECT TO authenticated
  USING (id_establecimiento = mi_establecimiento());
CREATE POLICY con_alta ON control_lechero FOR INSERT TO authenticated
  WITH CHECK (id_establecimiento = mi_establecimiento());

CREATE POLICY det_ver ON control_lechero_detalle FOR SELECT TO authenticated
  USING (animal_mio(id_animal));
CREATE POLICY det_alta ON control_lechero_detalle FOR INSERT TO authenticated
  WITH CHECK (animal_mio(id_animal));
