CREATE TABLE establecimiento (
  id_establecimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80),
  dias_servicio_tacto integer DEFAULT 45,
  dias_parto_secado integer DEFAULT 60,
  dias_calostro integer DEFAULT 5,
  dias_lactancia_primer_celo integer DEFAULT 45,
  dias_lactancia_induccion integer DEFAULT 60,
  dias_aviso_alerta integer DEFAULT 7
);

CREATE TABLE usuario (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_establecimiento integer,
  nombre varchar(80),
  correo varchar(120),
  rol varchar(20),
  id_auth uuid UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  FOREIGN KEY (id_establecimiento) REFERENCES establecimiento(id_establecimiento)
);

CREATE TABLE animal (
  id_animal integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_establecimiento integer,
  caravana varchar(20),
  categoria varchar(20),
  estado_reproductivo varchar(20),
  fecha_nacimiento date,
  fecha_ingreso date,
  fecha_baja date,
  motivo_baja varchar(20),
  id_madre integer,
  FOREIGN KEY (id_establecimiento) REFERENCES establecimiento(id_establecimiento),
  FOREIGN KEY (id_madre) REFERENCES animal(id_animal),
  UNIQUE (id_establecimiento, caravana)
);

CREATE TABLE captura (
  id_captura uuid PRIMARY KEY,
  id_usuario integer,
  id_animal integer,
  fecha_hora timestamp DEFAULT now(),
  tipo_captura varchar(10),
  archivo text,
  texto text,
  transcripcion text,
  estado varchar(15) DEFAULT 'sincronizada',
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  FOREIGN KEY (id_animal) REFERENCES animal(id_animal)
);

CREATE TABLE evento (
  id_evento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_animal integer,
  id_captura uuid,
  id_usuario_confirma integer,
  tipo_evento varchar(15),
  fecha_evento date,
  tipo_servicio varchar(15),
  resultado_tacto varchar(10),
  edad_gestacional integer,
  motivo_secado varchar(20),
  sexo_ternero char(1),
  medicamento varchar(60),
  dias_retiro integer,
  cuarentena boolean,
  motivo_baja varchar(20),
  fecha_confirmacion timestamp,
  toro varchar(20),
  FOREIGN KEY (id_usuario_confirma) REFERENCES usuario(id_usuario),
  FOREIGN KEY (id_animal) REFERENCES animal(id_animal),
  FOREIGN KEY (id_captura) REFERENCES captura(id_captura)
);

CREATE TABLE alerta (
  id_alerta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_animal integer,
  id_evento_origen integer,
  tipo_alerta varchar(25),
  fecha_objetivo date,
  estado varchar(10),
  FOREIGN KEY (id_animal) REFERENCES animal(id_animal),
  FOREIGN KEY (id_evento_origen) REFERENCES evento(id_evento)
);

CREATE TABLE advertencia (
  id_advertencia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_evento integer,
  tipo_advertencia varchar(25),
  detalle text,
  resuelta boolean,
  FOREIGN KEY (id_evento) REFERENCES evento(id_evento)
);

CREATE TABLE retiro_leche (
  id_retiro integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_establecimiento integer,
  fecha date,
  litros integer,
  temperatura numeric(4,1),
  FOREIGN KEY (id_establecimiento) REFERENCES establecimiento(id_establecimiento)
);

CREATE TABLE control_lechero (
  id_control integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_establecimiento integer,
  fecha date,
  FOREIGN KEY (id_establecimiento) REFERENCES establecimiento(id_establecimiento)
);

CREATE TABLE control_lechero_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_control integer,
  id_animal integer,
  litros_manana numeric(5,1),
  litros_tarde numeric(5,1),
  ausente boolean,
  FOREIGN KEY (id_animal) REFERENCES animal(id_animal),
  FOREIGN KEY (id_control) REFERENCES control_lechero(id_control)
);

CREATE OR REPLACE FUNCTION public.mi_establecimiento() RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT id_establecimiento FROM usuario WHERE id_auth = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.mi_rol() RETURNS varchar
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT rol FROM usuario WHERE id_auth = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.animal_mio(p_id_animal integer) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM animal
                 WHERE id_animal = p_id_animal
                   AND id_establecimiento = public.mi_establecimiento())
$$;

