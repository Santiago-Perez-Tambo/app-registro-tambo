CREATE POLICY est_ver ON establecimiento FOR SELECT TO authenticated
  USING (id_establecimiento = mi_establecimiento());
CREATE POLICY est_editar ON establecimiento FOR UPDATE TO authenticated
  USING (id_establecimiento = mi_establecimiento() AND mi_rol() = 'propietario');

CREATE POLICY usu_ver ON usuario FOR SELECT TO authenticated
  USING (id_establecimiento = mi_establecimiento());

CREATE POLICY ani_ver ON animal FOR SELECT TO authenticated
  USING (id_establecimiento = mi_establecimiento());
CREATE POLICY ani_alta ON animal FOR INSERT TO authenticated
  WITH CHECK (id_establecimiento = mi_establecimiento() AND mi_rol() = 'propietario');
CREATE POLICY ani_editar ON animal FOR UPDATE TO authenticated
  USING (id_establecimiento = mi_establecimiento() AND mi_rol() = 'propietario');

CREATE POLICY cap_ver ON captura FOR SELECT TO authenticated
  USING (animal_mio(id_animal));
CREATE POLICY cap_estado ON captura FOR UPDATE TO authenticated
  USING (animal_mio(id_animal) AND mi_rol() IN ('propietario', 'asesor'));

CREATE POLICY eve_ver ON evento FOR SELECT TO authenticated
  USING (animal_mio(id_animal));
CREATE POLICY eve_alta ON evento FOR INSERT TO authenticated
  WITH CHECK (animal_mio(id_animal) AND mi_rol() IN ('propietario', 'asesor'));
CREATE POLICY eve_confirmar ON evento FOR UPDATE TO authenticated
  USING (animal_mio(id_animal) AND mi_rol() IN ('propietario', 'asesor'));

CREATE POLICY ale_ver ON alerta FOR SELECT TO authenticated
  USING (animal_mio(id_animal));
CREATE POLICY ale_editar ON alerta FOR UPDATE TO authenticated
  USING (animal_mio(id_animal) AND mi_rol() IN ('propietario', 'asesor'));

CREATE POLICY adv_ver ON advertencia FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM evento e WHERE e.id_evento = advertencia.id_evento
                 AND animal_mio(e.id_animal)));
CREATE POLICY adv_resolver ON advertencia FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM evento e WHERE e.id_evento = advertencia.id_evento
                 AND animal_mio(e.id_animal))
         AND mi_rol() IN ('propietario', 'asesor'));

CREATE POLICY ret_ver ON retiro_leche FOR SELECT TO authenticated
  USING (id_establecimiento = mi_establecimiento());
CREATE POLICY ret_alta ON retiro_leche FOR INSERT TO authenticated
